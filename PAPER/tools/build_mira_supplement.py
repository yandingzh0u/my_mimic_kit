def write_tex(name, lines):
    (GENERATED / (name + '.tex')).write_text(
        '% Generated by PAPER/tools/build_mira_supplement.py.\n' + '\n'.join(lines) + '\n')


def row(*cells):
    return ' & '.join(map(str, cells)) + r' \\'


def cell(value, best, decimals=5):
    if value is None:
        return r'\textemdash'
    formatted = f'{value:.{decimals}f}'
    return r'\textbf{' + formatted + '}' if value == best else formatted


def support_labels(trace, steps, hz, protocol):
    sole = trace['ref_sole'][:steps + 1, ..., :2].astype(np.float64)
    sole_speed = np.linalg.norm(np.gradient(sole, 1 / hz, axis=0), axis=-1)
    plant = ((trace['ref_lowest'][:steps + 1] <= protocol['reference_plant_max_sole_clearance_m'])
             & (sole_speed <= protocol['reference_plant_max_speed_m_s']))
    ground = trace['foot_force'][1:steps + 1] >= protocol['minimum_simulated_normal_contact_force_n']
    return plant[1:], ground


def quality_metrics(trace, steps, protocol):
    hz = int(trace['hz'])
    active = trace['active'][:steps + 1]
    if hz not in (30, 60) or active.shape != (steps + 1, 256) or not active.all():
        raise ValueError('Motion-quality trace is missing aligned timesteps')
    stride = hz // 30
    body = trace['body'][:steps + 1:stride].astype(np.float64)
    ref = trace['ref_body'][:steps + 1:stride].astype(np.float64)
    speed = np.linalg.norm(np.diff(body[:, :, 0, :2], axis=0), axis=-1)
    ref_speed = np.linalg.norm(np.diff(ref[:, :, 0, :2], axis=0), axis=-1)
    speed -= speed.mean(axis=0)
    ref_speed -= ref_speed.mean(axis=0)
    pearson = (speed * ref_speed).sum(axis=0) / (np.linalg.norm(speed, axis=0)
                                                * np.linalg.norm(ref_speed, axis=0))
    plant, ground = support_labels(trace, steps, hz, protocol)
    support = plant & ground
    return dict(
        root_horizontal_speed_correlation=float(pearson.mean()),
        support_iou=float(support.sum() / (plant | ground).sum()),
        planted_slip_cm_s=float(100 * trace['sole_speed'][1:steps + 1][support].mean(dtype=np.float64)),
        body_jerk_m_s3=float((30**3 * np.linalg.norm(np.diff(body, n=3, axis=0), axis=-1)).mean()),
    )


def read_quality(tracking):
    # The original captures have one shared provenance file. Fresh captures
    # written by record_motion_quality.py carry a hash next to each trace.
    archive = AUDIT / 'results.json'
    archive_protocol = json.loads(archive.read_text())['protocol'] if archive.exists() else {}
    protocol = dict(
        training_seed=0, evaluation_seed=0, episodes_per_motion_and_method=256,
        aligned_start='phase0', differentiation_rate_hz=30,
        reference_plant_max_sole_clearance_m=.04, reference_plant_max_speed_m_s=.15,
        minimum_simulated_normal_contact_force_n=5,
        checkpoint_sha256={},
    )
    results, sources = {}, {}
    for motion in CONTACT:
        results[motion], sources[motion], protocol['checkpoint_sha256'][motion] = {}, {}, {}
        for method in METHODS:
            path = AUDIT / f'{motion}_{method}.npz'
            metadata = path.with_suffix('.json')
            if metadata.exists():
                meta = json.loads(metadata.read_text())
                if (meta['n'], meta['evaluation_seed'], meta['start'], meta['training_samples']) != (
                        256, 0, 'phase0', 524288000):
                    raise ValueError(f'Unexpected motion-quality protocol: {metadata}')
                model_hash = meta['model_sha256']
            else:
                model_hash = archive_protocol['checkpoint_sha256'][motion][method]
            if model_hash != tracking['results'][method][motion]['model_sha256']:
                raise ValueError(f'Evaluation checkpoint mismatch: {motion}/{method}')
            protocol['checkpoint_sha256'][motion][method] = model_hash
            with np.load(path) as trace:
                results[motion][method] = quality_metrics(trace, HORIZON[motion], protocol)
            sources[motion][method] = source_record(path)
    macro = {method: {key: float(np.mean([results[m][method][key] for m in CONTACT]))
                      for key, *_ in QUALITY} for method in METHODS}
    return dict(protocol=protocol, steps={m: HORIZON[m] for m in CONTACT},
                results=results, macro=macro, sources=sources)


def read_ablations():
    variants = {}
    for variant in VARIANTS:
        folder = ABLATIONS / variant
        summary = json.loads((folder / 'summary.json').read_text())
        meta, protocol = summary['metadata'], summary['protocol']
        if (meta['seed'] != 0 or meta['motion'] != 'backflip'
                or meta['checkpoint']['samples'] != 524288000
                or protocol['requested_steps'] != 60 or protocol['num_episodes'] != 256
                or protocol['start_mode'] != 'phase0' or not protocol['no_automatic_reset']
                or not protocol['deterministic_mean_action']):
            raise ValueError(f'Unexpected Backflip evaluation protocol: {variant}')
        path = folder / 'timeseries.npz'
        with np.load(path) as trace:
            alive = trace['alive']
            values = trace['tracking_error'][..., :len(TRACKING_KEYS)]
            if (tuple(trace['tracking_error_names'][:len(TRACKING_KEYS)]) != TRACKING_KEYS
                    or alive.shape[1] != 256 or values.shape[:2] != alive.shape):
                raise ValueError(f'Unexpected Backflip trace schema: {variant}')
            windows = {}
            for steps in (26, 60):
                if len(alive) >= steps and alive[:steps].all():
                    if not np.isfinite(values[:steps]).all():
                        raise ValueError(f'Nonfinite Backflip results: {variant}')
                    windows[str(steps)] = values[:steps].mean(axis=(0, 1), dtype=np.float64).tolist()
        if '26' not in windows:
            raise ValueError(f'Missing common 26-step window: {variant}')
        variants[variant] = dict(windows=windows, evaluated_steps=protocol['executed_steps'],
                                 training_samples=meta['checkpoint']['samples'],
                                 model_file=str(ROOT.joinpath(meta['model_file']).relative_to(ROOT)),
                                 model_sha256=meta['model_sha256'],
                                 source=source_record(path))
    return variants


def main_tables(quality, ablations):
    lines = [r'\begin{table}[t]', r'\caption{Motion quality averaged over Sofa Sit, Box Carry,',
             r'and Soccer. The arrows indicate the preferred direction.}',
             r'\label{tab:motion_quality}', r'\centering\footnotesize',
             r'\setlength{\tabcolsep}{3pt}',
             r'\begin{tabular}{@{}lcccc@{}}\toprule', row('Metric', *METHODS), r'\midrule']
    for key, label, decimals, scale in QUALITY:
        values = [quality['macro'][m][key] * scale for m in METHODS]
        best = (max if scale == 100 or key.endswith('correlation') else min)(values)
        lines.append(row(label, *(cell(v, best, decimals) for v in values)))
    write_tex('mira_motion_quality_table', lines + [r'\bottomrule\end{tabular}', r'\end{table}'])

    lines = [r'\begin{table}[t]', r'\caption{Backflip ablations on matched prefixes.',
             r'Lower is better. Compare rows within each window.}', r'\label{tab:ablation}',
             r'\centering\footnotesize', r'\setlength{\tabcolsep}{3pt}',
             r'\begin{tabular}{@{}lrrr@{}}\toprule',
             row('Configuration', 'Body pos.', 'Body rot.', 'DoF vel.'),
             row('', '[m]', '[rad]', '[rad/s]')]
    for count, variants in ((60, ('mira', 'signed', 'no_sqrt')), (26, ('mira', 'no_b'))):
        lines.extend([r'\midrule', rf'\multicolumn{{4}}{{@{{}}l}}{{\textit{{Steps 1--{count}}}}} \\'])
        values = np.array([ablations[v]['windows'][str(count)][2:5] for v in variants])
        for v, nums in zip(variants, values):
            lines.append(row(VARIANTS[v], *(cell(x, best, 4) for x, best in zip(nums, values.min(0)))))
    write_tex('mira_matched_ablation_table', lines + [r'\bottomrule\end{tabular}', r'\end{table}'])


def appendix_tables(tracking, quality, ablations):
    header = [('Root pos.', 'm'), ('Root rot.', 'rad'), ('Body pos.', 'm'),
              ('Body rot.', 'rad'), ('DoF vel.', 'rad/s'), ('Root vel.', 'm/s'),
              ('Root ang. vel.', 'rad/s')]
    lines = [r'\begin{table}[!ht]', r'\caption{All seven tracking errors by motion. Each error is',
             r'lower-is-better; bold marks the minimum within a motion. A dash indicates',
             r'no full-window record.}', r'\label{tab:per_motion_errors}', r'\centering\small',
             r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}llrrrrrrr@{}}\toprule',
             row('Motion', 'Method', *(label for label, _ in header)),
             row('', '', *(f'[{unit}]' for _, unit in header))]
    for motion in MOTIONS:
        lines.append(r'\midrule')
        values = [tracking['results'][m][motion]['error'] for m in METHODS]
        best = np.min([v for v in values if v is not None], axis=0)
        for i, (method, nums) in enumerate(zip(METHODS, values)):
            lines.append(row(tracking['motions'][motion] if i == 0 else '', method,
                             *(cell(v, b) for v, b in zip(nums or [None] * len(best), best))))
    write_tex('mira_per_motion_table', lines + [r'\bottomrule\end{tabular*}', r'\end{table}'])

    lines = [r'\begin{table}[!ht]', r'\caption{Motion quality by motion. Ground support is',
             r'foot--ground contact, including in the sofa and box scenes.}',
             r'\label{tab:per_motion_quality}', r'\centering\small',
             r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}llrrrr@{}}\toprule',
             row('Motion', 'Method', r'Speed $r$ $\uparrow$', r'Support IoU [\%] $\uparrow$',
                 r'Stance slip [cm/s] $\downarrow$', r'Jerk [m/s$^3$] $\downarrow$')]
    for motion in CONTACT:
        lines.append(r'\midrule')
        data = quality['results'][motion]
        vals = [[data[m][key] * scale for key, _, _, scale in QUALITY] for m in METHODS]
        best = [choose(v) for choose, v in zip((max, max, min, min), zip(*vals))]
        for i, (method, nums) in enumerate(zip(METHODS, vals)):
            lines.append(row(tracking['motions'][motion] if i == 0 else '', method,
                             *(cell(v, b, spec[2]) for v, b, spec in zip(nums, best, QUALITY))))
    write_tex('mira_per_motion_quality_table', lines + [r'\bottomrule\end{tabular*}', r'\end{table}'])

    lines = [r'\begin{table}[!ht]', r'\caption{All tracking errors for Backflip ablations. Each panel',
             r'uses one prefix common to every row in that panel. Units match',
             r'Table~\ref{tab:per_motion_errors}; lower is better.}',
             r'\label{tab:full_ablation}', r'\centering\small', r'\setlength{\tabcolsep}{3pt}',
             r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrrrrrrr@{}}\toprule',
             row('Configuration', *(label for label, _ in header))]
    for steps in ('60', '26'):
        lines.extend([r'\midrule', rf'\multicolumn{{8}}{{@{{}}l}}{{\textit{{Steps 1--{steps}}}}} \\'])
        keys = [k for k, info in ablations.items() if steps in info['windows']]
        values = np.array([ablations[k]['windows'][steps] for k in keys])
        best = values.min(axis=0)
        lines.extend(row(VARIANTS[k], *(cell(v, b, 4) for v, b in zip(nums, best)))
                     for k, nums in zip(keys, values))
    write_tex('mira_full_ablation_table', lines + [r'\bottomrule\end{tabular*}', r'\end{table}'])


def style():
    plt.rcParams.update({
        'font.family': 'DejaVu Sans', 'font.size': 7.4, 'pdf.fonttype': 42,
        'axes.spines.top': False, 'axes.spines.right': False, 'axes.edgecolor': '#65717a',
        'axes.axisbelow': True, 'grid.color': '#e0e5e8', 'grid.linewidth': .65,
        'xtick.major.size': 2.5, 'ytick.major.size': 2.5, 'savefig.facecolor': 'white',
    })


def save(fig, name):
    fig.savefig(FIGURES / (name + '.pdf'))
    fig.savefig(FIGURES / (name + '.png'), dpi=300)
    plt.close(fig)


def soccer_figure(quality):
    motion = 'soccer_cmu_10_02'
    steps = quality['steps'][motion]
    thresholds = quality['protocol']
    runs, reference, sources = {}, None, {}
    for method in METHODS:
        path = AUDIT / f'{motion}_{method}.npz'
        with np.load(path) as f:
            hz = int(f['hz'])
            if hz != 60 or not f['active'][:steps + 1].all():
                raise ValueError(f'Unexpected Soccer timing data: {method}')
            planar = f['body'][:steps + 1:2, :, 0, :2].astype(np.float64)
            speed = 30 * np.linalg.norm(np.diff(planar, axis=0), axis=-1).mean(1)
            plant, ground = support_labels(f, steps, hz, thresholds)
            contact = ground.mean(1) >= .5
            runs[method] = (speed, contact)
            if reference is None:
                planar = f['ref_body'][:steps + 1:2, :, 0, :2].astype(np.float64)
                ref_speed = 30 * np.linalg.norm(np.diff(planar, axis=0), axis=-1).mean(1)
                reference = (ref_speed, plant.mean(1) >= .5)
        sources[method] = source_record(path)

    fig, (top, bottom) = plt.subplots(2, sharex=True, figsize=(3.42, 2.85),
                                     gridspec_kw={'height_ratios': (1.07, 1)})
    fig.subplots_adjust(left=.205, right=.985, top=.91, bottom=.125, hspace=.35)
    names = ('Reference', *METHODS)
    for name, (speed, contacts) in {'Reference': reference, **runs}.items():
        t_speed = (np.arange(1, speed.size + 1) - .5) / 30
        top.plot(t_speed, speed, color=COLORS[name], linestyle=STYLES[name],
                 lw=1.45 if name in ('MIRA', 'Reference') else .95, label=name,
                 zorder=4 if name in ('MIRA', 'Reference') else 2)
        i = names.index(name)
        for j, y in enumerate((4 - i, -2 - i)):
            bottom.axhline(y, color='#ebedf0', lw=3)
            on = np.diff(np.r_[False, contacts[:, j], False].astype(np.int8))
            spans = (np.flatnonzero(on == 1), np.flatnonzero(on == -1))
            for start, stop in zip(*spans):
                bottom.hlines(y, start / 60, stop / 60, color=COLORS[name], lw=3)
    top.set(ylabel='Root speed [m/s]', ylim=(0, None))
    top.grid(axis='y')
    handles, labels = top.get_legend_handles_labels()
    fig.legend(handles, labels, loc='upper center', bbox_to_anchor=(.54, 1.0),
               ncol=5, frameon=False, fontsize=6.6, handlelength=1.65, columnspacing=.8)
    bottom.set(yticks=[2, -4], yticklabels=['Left foot', 'Right foot'],
               ylim=(-6.7, 4.7), xlim=(0, steps / 60), xlabel='Reference time [s]')
    bottom.tick_params(axis='y', length=0, pad=3)
    bottom.xaxis.set_major_locator(MultipleLocator(.5))
    bottom.grid(axis='x')
    save(fig, 'mira_soccer_timing')
    return sources


def velocity_figure(tracking):
    fig, axs = plt.subplots(1, 2, figsize=(6.78, 2.15), sharey=True)
    fig.subplots_adjust(left=.093, right=.986, top=.80, bottom=.22, wspace=.15)
    for ax, motion in zip(axs, ('roll', 'climb')):
        for method in METHODS:
            log = ROOT / tracking['curve_logs'][method][motion]
            if (method, motion) == ('ADD', 'climb'):
                resumed = ROOT / tracking['results'][method][motion]['source']['path']
                logs = (log, resumed)
            else:
                logs = (log,)
            points = {r['Samples']: r['Dof_Vel_Err'] for path in logs for r in load_lines(path)
                      if 'Dof_Vel_Err' in r}
            x = np.array(sorted(points))
            ax.plot(x / 1e8, [points[s] for s in x], color=COLORS[method],
                    linestyle=STYLES[method], label=method, lw=1.0 if method != 'MIRA' else 1.5)
        ax.set(title=tracking['motions'][motion], xlim=(0, 8.0))
        ax.grid(axis='y')
    axs[0].set_ylabel('DoF velocity error [rad/s]')
    fig.text(.54, .035, r'Environment samples [$10^8$]', ha='center')
    handles, labels = axs[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='upper center', bbox_to_anchor=(.54, 1.0),
               ncol=4, frameon=False)
    save(fig, 'mira_roll_climb_velocity')


def main():
    tracking = json.loads((GENERATED / 'mira_tracking_results.json').read_text())
    quality, ablations = read_quality(tracking), read_ablations()
    main_tables(quality, ablations)
    appendix_tables(tracking, quality, ablations)
    style()
    quality['soccer_trace_sources'] = soccer_figure(quality)
    velocity_figure(tracking)
    (GENERATED / 'mira_supplement_results.json').write_text(
        json.dumps(dict(motion_quality=quality, ablations=ablations,
                        tracking_columns=[key for key, _, _ in METRICS]),
                   indent=2, allow_nan=False) + '\n')


if __name__ == '__main__':
    main()
