"""Export the six motions in the current manuscript from measured tracking data."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

from build_mira_experiments import GENERATED, METHODS, METRICS, PAPER, ROOT, load_lines, run_path


MOTIONS = ('sofa003', 'carry_box', 'soccer_cmu_10_02', 'backflip', 'climb', 'roll')
CONTACT = MOTIONS[:3]
HORIZON = dict(zip(MOTIONS, (171, 197, 129, 60, 299, 60)))
LABELS = ('Sofa Sit', 'Box Carry', 'Soccer', 'Backflip', 'Climb', 'Roll')
TRACKING_KEYS = ('root_pos_err', 'root_rot_err', 'body_pos_err', 'body_rot_err',
                 'dof_vel_err', 'root_vel_err', 'root_ang_vel_err')
ADD_CLIMB = ROOT / 'output/add_climb_2k_8192_seed0_resume500_v3/train_metrics.jsonl'


def source_record(path):
    return dict(path=str(path.relative_to(ROOT)), sha256=hashlib.sha256(path.read_bytes()).hexdigest())


def recorded_test(path, steps):
    rows = [(i, r) for i, r in enumerate(load_lines(path), 1)
            if r.get('Test_Episode_Length_Start0', r['Test_Episode_Length']) == steps]
    if not rows:
        return dict(error=None, source=source_record(path), reason='No logged full-horizon test')
    line, row = max(rows, key=lambda entry: entry[1]['Samples'])
    return dict(error=[float(row[k]) for k, _, _ in METRICS], source=source_record(path),
                source_line=line, steps=steps, samples=row['Samples'], iteration=row['Iteration'],
                episodes=row.get('Test_Episodes_Start0', row['Test_Episodes']))


def checkpoint_test(motion, method, steps):
    directory = PAPER / 'build/interaction_eval' / motion / method
    report = json.loads((directory / 'summary.json').read_text())
    if ((report['task'], report['method'], report['n'], report['start'], report['training_samples'])
            != (motion, method, 256, 'phase0', 524288000)
            or tuple(report['tracking_columns']) != TRACKING_KEYS):
        raise ValueError(f'Unexpected evaluation protocol: {directory}')
    path = directory / 'trajectories.npz'
    with np.load(path) as traces:
        active = traces['active']
        values = traces['tracking_error']
        if (active.shape[0] < steps or active.shape[1] != report['n']
                or not active[:steps].all() or values.shape != (*active.shape, len(METRICS))
                or not np.isfinite(values[:steps]).all()):
            raise ValueError(f'Missing aligned frames in {path}')
        err = values[:steps].mean(axis=(0, 1), dtype=np.float64)
    return dict(error=err.tolist(), source=source_record(path), steps=steps, episodes=report['n'],
                samples=report['training_samples'], model_sha256=report['model_sha256'],
                model_run=report['run'])


def average(results, motions):
    values = [results[m]['error'] for m in motions]
    return None if any(v is None for v in values) else np.mean(values, axis=0).tolist()


def build():
    records, curve_logs = {}, {}
    for method in METHODS:
        results, curves = {}, {}
        for motion in MOTIONS:
            if motion in CONTACT:
                result = checkpoint_test(motion, method, HORIZON[motion])
                log = ROOT / result['model_run'] / 'train_metrics.jsonl'
            else:
                log = run_path(method, motion) / 'train_metrics.jsonl'
                endpoint = ADD_CLIMB if (method, motion) == ('ADD', 'climb') else log
                result = recorded_test(endpoint, HORIZON[motion])
            curves[motion] = str(log.relative_to(ROOT))
            results[motion] = result
        records[method], curve_logs[method] = results, curves
    return dict(motions=dict(zip(MOTIONS, LABELS)), aligned_steps=HORIZON, seed=0,
                metrics=[key for key, _, _ in METRICS], results=records,
                macro_six={m: average(records[m], MOTIONS) for m in METHODS},
                macro_contact={m: average(records[m], CONTACT) for m in METHODS},
                curve_logs=curve_logs)


def panel(aggregates):
    lines = [r'\begin{tabular}{lcccc}\toprule',
             r'Metric $\downarrow$ & AMP & DeepMimic & ADD & MIRA \\', r'\midrule']
    for i, (_, label, unit) in enumerate(METRICS):
        best = min(v[i] for v in aggregates.values() if v is not None)
        cells = []
        for method in METHODS:
            v = aggregates[method]
            if v is None:
                cells.append(r'\textemdash')
            else:
                text = f'{v[i]:.5f}'
                cells.append(r'\textbf{' + text + '}' if v[i] == best else text)
        lines.append(' & '.join([f'{label} [{unit}]', *cells]) + r' \\')
    return lines + [r'\bottomrule\end{tabular}']


def main():
    data = build()
    lines = [
        '% Generated by PAPER/tools/build_mira_tracking_table.py.',
        r'\begin{table}[t]',
        r'\caption{Tracking errors averaged equally over the six motions.',
        r'Climb uses $299$ control steps. AMP has no full-window record',
        r'for Backflip or Climb. Bold marks the lowest available error.}',
        r'\label{tab:main}',
        r'\centering\footnotesize',
        r'\setlength{\tabcolsep}{3pt}',
        *panel(data['macro_six']),
        r'\end{table}',
    ]
    (GENERATED / 'mira_tracking_table.tex').write_text('\n'.join(lines) + '\n')
    (GENERATED / 'mira_tracking_results.json').write_text(json.dumps(data, indent=2, allow_nan=False) + '\n')


if __name__ == '__main__':
    main()
